#!/usr/bin/env bash
# index.sh [project root]: regenerate .keep/INDEX.md, the list of features and tracks with the command to
# start each. Only rewritten when its content changes.
set -uo pipefail
. "$(dirname "$0")/common.sh"
root="${1:-$PWD}"
keep=$(keep_dir "$root")
[ -d "$keep" ] || exit 0
idle="${KEEP_IDLE_DAYS:-14}"
# Chats run side by side, so each run writes its own temporary file, inside .state/ so git never sees
# one left behind by a run that was killed.
mkdir -p "$keep/.state" || exit 0
[ -f "$keep/.state/.gitignore" ] || printf '*\n' > "$keep/.state/.gitignore"
tmp=$(mktemp "$keep/.state/INDEX.XXXXXX") || exit 0
trap 'rm -f "$tmp"' EXIT

{
  echo "# keep index"
  echo
  echo "<!-- Generated by keep at every chat start and state save. Edits here are overwritten. -->"
  echo
  rows=$(track_rows "$keep")
  if [ -z "$rows" ]; then
    echo 'No tracks yet. Create one with `/keep:start`.'
  else
    echo "| Track | Current work | Last update | Start it with |"
    echo "| --- | --- | --- | --- |"
    while IFS=$'\t' read -r f t cur updated days; do
      note=""
      [ "$days" -ge "$idle" ] && note=", idle $days days: \`/keep:close $f/$t\`?"
      printf '| %s/%s | %s | %s%s | `/keep:start %s` |\n' "$f" "$t" \
        "$(printf '%s' "${cur:-none}" | sed 's/|/\\|/g')" "$updated" "$note" "$(start_arg "$keep" "$f" "$t")"
    done <<<"$rows"
  fi
  archived=$(find "$keep/_archive" -mindepth 2 -maxdepth 2 -type d 2>/dev/null | wc -l | tr -d ' ')
  if [ "$archived" -gt 0 ]; then
    echo
    echo "Archived tracks: $archived, in \`_archive/\`."
  fi
} > "$tmp" || { rm -f "$tmp"; exit 0; }

if cmp -s "$tmp" "$keep/INDEX.md"; then rm -f "$tmp"; else mv "$tmp" "$keep/INDEX.md"; fi

# The index is derived from the state files, so it stays out of git.
gi="$keep/.gitignore"
if ! grep -qxF 'INDEX.md' "$gi" 2>/dev/null; then
  [ -s "$gi" ] && [ -n "$(tail -c 1 "$gi")" ] && echo >> "$gi"
  echo 'INDEX.md' >> "$gi"
fi
exit 0
